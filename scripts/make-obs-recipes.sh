#!/usr/bin/env bash
# Create an OBS package directory from a source package built by make-source-package.sh
# (with SERIES="" so the version has no ~series suffix).
#
# One payload (the orig tarball = unmodified files of the upstream .deb) and three recipes:
#   *.dsc + debian.tar.xz   -> Debian/Ubuntu
#   PKG.spec                -> Fedora/openSUSE   (Requires/scriptlets from the upstream .rpm, if given)
#   PKGBUILD                -> Arch Linux        (depends/install script from the upstream Arch package, if given)
#
# Usage: make-obs-recipes.sh WORKDIR OUTDIR
# Environment: LICENSE, GH_REPO; optional RPM=/path/upstream.rpm, ARCHPKG=/path/upstream.pkg.tar.zst
# Needs: dpkg-deb, rpm (only with RPM), bsdtar + zstd (only with ARCHPKG), sha256sum

set -euo pipefail
WORKDIR="$1"; OUT="$2"
: "${LICENSE:?}" "${GH_REPO:?}"
# shellcheck disable=SC1091
. "$WORKDIR/result.env"     # PKG SRCVER UPSTREAM ORIG DEB
die() { echo "ERROR: $*" >&2; exit 1; }

rm -rf "$OUT"; mkdir -p "$OUT"
ORIGNAME="$(basename "$ORIG")"
cp "$ORIG" "$OUT/"
cp "$WORKDIR/${PKG}_${SRCVER}.dsc" "$WORKDIR/${PKG}_${SRCVER}.debian.tar.xz" "$OUT/"

# ---------------------------------------------------------------- description
DESC="$(dpkg-deb -f "$DEB" Description)"
SUMMARY="$(head -n1 <<<"$DESC")"; [ -n "$SUMMARY" ] || SUMMARY="$PKG"
LONG="$(tail -n +2 <<<"$DESC" | sed -e 's/^ //' -e 's/^\.$//')"; [ -n "$LONG" ] || LONG="$SUMMARY"
LONG="$LONG

Unofficial repackage of the official upstream release from
https://github.com/$GH_REPO (prebuilt files, not built from source)."

# ---------------------------------------------------------------- rpm metadata
REQUIRES=""; declare -A SCRIPT=()
if [ -n "${RPM:-}" ]; then
  REQUIRES="$(rpm -qp --requires "$RPM" 2>/dev/null | grep -v -e '^rpmlib(' -e '^/bin/sh$' | sort -u || true)"
  for t in PREIN POSTIN PREUN POSTUN; do
    s="$(rpm -qp --qf "%{$t}" "$RPM" 2>/dev/null || true)"
    [ "$s" != "(none)" ] && [ -n "$s" ] && SCRIPT[$t]="$s"
  done
fi

{
  cat <<EOF
# Generated by obs-sync/make-obs-recipes.sh. Repack of prebuilt upstream files.
%global debug_package %{nil}
%global __os_install_post %{nil}
%global _build_id_links none

Name:           $PKG
Version:        $UPSTREAM
Release:        0
Summary:        $SUMMARY
License:        $LICENSE
URL:            https://github.com/$GH_REPO
Source0:        $ORIGNAME
Source1:        $PKG-rpmlintrc
ExclusiveArch:  x86_64
AutoReqProv:    no
EOF
  while IFS= read -r r; do [ -n "$r" ] && echo "Requires:       $r"; done <<<"$REQUIRES"
  cat <<EOF

%description
$LONG

%prep
%setup -q -n $PKG-$UPSTREAM

%build

%install
mkdir -p %{buildroot}
cp -a . %{buildroot}/
( cd %{buildroot} && find . \\( -type f -o -type l \\) | sed -e 's|^\\.||' -e 's|%|%%%%|g' -e 's|^|"|' -e 's|\$|"|' ) > files.list
# own the package's directories, except standard system directories (openSUSE checks ownership)
( cd %{buildroot} && find . -mindepth 1 -type d | sed -e 's|^\\.||' \\
  | grep -Ev '^/(etc|opt|usr|usr/(bin|sbin|lib|lib64|libexec|share)|usr/share/(applications|icons|doc|licenses|man|man/man[0-9]|pixmaps|metainfo|mime|mime/packages))\$' \\
  | sed -e 's|%|%%%%|g' -e 's|^|%%dir "|' -e 's|\$|"|' ) >> files.list

%files -f files.list
EOF
  declare -A SEC=([PREIN]=pre [POSTIN]=post [PREUN]=preun [POSTUN]=postun)
  for t in PREIN POSTIN PREUN POSTUN; do
    if [ -n "${SCRIPT[$t]:-}" ]; then printf '\n%%%s\n%s\n' "${SEC[$t]}" "${SCRIPT[$t]}"; fi
  done
} > "$OUT/$PKG.spec"

# openSUSE runs rpmlint on every build; a repack of prebuilt files triggers many findings.
echo 'addFilter(".*")' > "$OUT/$PKG-rpmlintrc"

# ---------------------------------------------------------------- Arch metadata
DEPENDS=""; INSTALL=""
if [ -n "${ARCHPKG:-}" ]; then
  DEPENDS="$(bsdtar -xOf "$ARCHPKG" .PKGINFO 2>/dev/null | awk -F' = ' '$1=="depend"{print $2}' || true)"
  if bsdtar -tf "$ARCHPKG" .INSTALL >/dev/null 2>&1; then
    bsdtar -xOf "$ARCHPKG" .INSTALL > "$OUT/$PKG.install"; INSTALL="$PKG.install"
  fi
fi
q() { printf "'%s'" "${1//\'/\'\\\'\'}"; }
{
  echo "# Generated by obs-sync/make-obs-recipes.sh. Repack of prebuilt upstream files."
  echo "pkgname=$PKG"
  echo "pkgver=${UPSTREAM//[-~:]/_}"
  echo "pkgrel=1"
  echo "pkgdesc=$(q "$SUMMARY")"
  echo "arch=('x86_64')"
  echo "url=$(q "https://github.com/$GH_REPO")"
  echo "license=($(q "$LICENSE"))"
  printf 'depends=('; while IFS= read -r d; do [ -n "$d" ] && printf '%s ' "$(q "$d")"; done <<<"$DEPENDS"; echo ')'
  echo "options=('!strip' '!debug' '!emptydirs' '!lto')"
  [ -n "$INSTALL" ] && echo "install=$INSTALL"
  echo "source=($(q "$ORIGNAME"))"
  echo "sha256sums=('$(sha256sum "$ORIG" | awk '{print $1}')')"
  echo
  echo 'package() {'
  echo "  cp -a \"\$srcdir/$PKG-$UPSTREAM/.\" \"\$pkgdir/\""
  echo '}'
} > "$OUT/PKGBUILD"

echo "==> OBS package in $OUT:"; ls -la "$OUT"
echo "    rpm Requires: $(grep -c . <<<"${REQUIRES:-}" || true) line(s), source: $(basename "${RPM:-none}")"
echo "    Arch depends: $(grep -c . <<<"${DEPENDS:-}" || true) line(s), source: $(basename "${ARCHPKG:-none}")"
